/**
 * 同音字與形近字題材：選對的字填進句子、找出句子裡的錯字。
 * 句子都自編；干擾字是常見的同音字或形近字。
 */
import type { Lv } from './types';

/** 選字填空：句子裡的（　）要填 right，wrong 為同音或形近的干擾字 */
export interface CharChoiceItem {
  sentence: string;
  right: string;
  wrong: string[];
  level: Lv;
  explain: string;
}

const c = (sentence: string, right: string, wrong: string, level: Lv, explain: string): CharChoiceItem => ({
  sentence,
  right,
  wrong: wrong.split(','),
  level,
  explain,
});

