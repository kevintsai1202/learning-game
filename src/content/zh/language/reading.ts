/**
 * 閱讀小短文題材：自編短文（故事、童詩、日記、說明短文），每篇 3 題選擇題。
 * 短文 60～150 字；題幹只放問題，短文放在 visual 的 passage。
 */
import type { Lv } from './types';

/** 一題閱讀題：right 為正解，wrong 為三個干擾項 */
export interface ReadingQuestion {
  prompt: string;
  right: string;
  wrong: string[];
  /** 題目類型：事實、因果、主旨、心情（決定課綱代碼） */
  type: 'fact' | 'cause' | 'main' | 'mood';
  explain: string;
}

export interface ReadingPassage {
  /** 短文 id（題目 id 的一部分，新增請加在最後，不要改順序） */
  id: string;
  title: string;
  /** 文體 */
  genre: 'story' | 'poem' | 'diary' | 'explain';
  text: string;
  level: Lv;
  /** 每篇至少 3 題（建議 5 題）；出題時每回合隨機取 3 題，讓同一篇短文再出現時題目也有變化 */
  questions: ReadingQuestion[];
}

const rq = (type: ReadingQuestion['type'], prompt: string, right: string, wrong: string, explain: string): ReadingQuestion => ({
  type,
  prompt,
  right,
  wrong: wrong.split('|'),
  explain,
});

