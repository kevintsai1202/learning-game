/** 關聯詞：sentence 有兩個（　），填入同一組關聯詞 right；干擾項是其他組 */
export interface ConnectiveItem {
  sentence: string;
  /** CONNECTIVES 的索引 */
  right: number;
  level: Lv;
  /** 不能當干擾項的關聯詞索引（例如「一邊…一邊」的句子，「先…再」也說得通） */
  exclude?: number[];
}

/** 關聯詞組（顯示用 text；朗讀時「…」唸成停頓） */
export const CONNECTIVES: string[] = ['因為…所以', '如果…就', '雖然…但是', '先…再', '不但…而且', '一邊…一邊'];

