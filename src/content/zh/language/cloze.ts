import type { Lv } from './types';

/** 近義詞：a、b 意思接近；wrong 是三個意思不同（或相反）的詞 */
export interface SynonymItem {
  a: string;
  b: string;
  wrong: string[];
  level: Lv;
}

const s = (a: string, b: string, wrong: string, level: Lv): SynonymItem => ({ a, b, wrong: wrong.split(','), level });

