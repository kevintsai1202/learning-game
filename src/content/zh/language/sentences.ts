/** 組合句用的人物（都是人，動作物件才不會不通順） */
const WHO = ['弟弟', '妹妹', '哥哥', '姊姊', '媽媽', '爸爸', '小明', '小美'];

/** 簡單的「動作＋東西」（主詞／動詞／受詞，只有一種通順排法） */
const VERB_OBJECT: [string, string][] = [
  ['吃', '蘋果'], ['吃', '香蕉'], ['吃', '麵包'], ['吃', '飯'],
  ['喝', '牛奶'], ['喝', '果汁'], ['喝', '水'],
  ['看', '書'], ['看', '電視'], ['看', '星星'],
  ['畫', '圖'], ['畫', '小花'], ['畫', '太陽'],
];

/** 「先…再…」的日常順序（前一件事要在後一件事之前才合理） */
const ROUTINES: [string, string][] = [
  ['洗手', '吃飯'], ['做功課', '玩遊戲'], ['刷牙', '睡覺'], ['穿鞋子', '出門'], ['洗澡', '睡覺'],
];

/** 「得」字句：動作＋得＋很＋形容詞 */
const DEGREE: [string, string][] = [
  ['跑得', '快'], ['唱得', '好聽'], ['寫得', '工整'], ['跳得', '高'], ['畫得', '漂亮'],
];

/** 全部排序題：固定句子加上程式組合句（組合句的 id 以句子本身為準，順序調整不會影響） */
export const ORDER_ITEMS: OrderItem[] = [
  ...FIXED_TEXT.map(([text, level], i): OrderItem => ({ id: `f${i + 1}`, steps: text.split('／'), level })),
  ...WHO.flatMap((who) => VERB_OBJECT.map(([v, obj]): OrderItem => ({ id: `s:${who}${v}${obj}`, steps: [who, v, obj], level: 1 }))),
  ...WHO.flatMap((who) => ROUTINES.map(([a, b]): OrderItem => ({ id: `r:${who}${a}${b}`, steps: [who, '先', a, '再', b], level: 2 }))),
  ...WHO.flatMap((who) => DEGREE.map(([v, adj]): OrderItem => ({ id: `d:${who}${v}${adj}`, steps: [who, v, '很', adj], level: 3 }))),
];

/** 標點符號的名稱 */
export const PUNCT_NAMES: Record<string, string> = {
  '，': '逗號',
  '。': '句號',
  '？': '問號',
  '！': '驚嘆號',
  '、': '頓號',
};

/** 標點填空：sentence 的（　）要填 right；options 為四個選項（含 right） */
export interface PunctItem {
  sentence: string;
  right: string;
  options: string[];
  level: Lv;
}

